w("// Wuerttemberg and Bavaria c. 1811 (docs/specs/aliados_fr_1812.md). No faction: the soldier classes are scope 1 (an Arma uniform needs a soldier")
w("// model); the items are scope 2 (Arsenal). Does not require hcl_fr.")
w("")
w("class CfgPatches\n{\n\tclass HCL_Reno_Teste\n\t{")
w('\t\tauthor = "Historical Clothing";')
w("\t\tunits[] = {};")
weapons = [cls_u(v) for v in VIDS + EIDS] + [f"HCL_H_Reno1811_{h[2]}" for h in HEAD]
w("\t\tweapons[] = {" + ", ".join(f'"{x}"' for x in weapons) + "};")
w("\t\trequiredVersion = 0.1;")
w('\t\trequiredAddons[] = {"A3_Characters_F"};')
w("\t};\n};\n")

w("class CfgVehicles\n{")
w("\tclass B_Soldier_base_F;\n")
