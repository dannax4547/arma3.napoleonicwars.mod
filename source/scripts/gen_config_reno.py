# Writes the text sources of the in-game TEST addon hcl_reno (Confederation of the Rhine infantry, lot 1: Wuerttemberg
# and Bavaria c. 1811, crested helmets): config.cpp, model.cfg and the materials (.rvmat). Copy of gen_config_italia.py
# (same base classes and conventions, one coat model, no elite coat yet); English names from nomes_en_aliados.py.
#   python gen_config_reno.py <project root> <variants dir> <out addon dir>
#   <variants dir>: folder of variantes_reno.json
import sys, os, json, re

ROOT, VDIR, SRC = sys.argv[1:4]
os.makedirs(os.path.join(SRC, "data"), exist_ok=True)
VAR = json.load(open(os.path.join(VDIR, "variantes_reno.json"), encoding="utf-8"))
ELI = {}
P = r"\hcl\hcl_reno"
VIDS, EIDS = sorted(VAR), sorted(ELI)
U_P3D = "hcl_u_reno1811"
# headgear entries: (p3d base, material base, class suffix, _co base)
HEAD = [(f"hcl_h_reno_raupenhelm_{t}", f"hcl_raupenhelm_{t}", f"Raupenhelm_{c}", f"hcl_raupenhelm_{t}")
        for t, c in (("wurttemberg", "Wurttemberg"), ("baviera", "Baviera"))]
# lot 2 (2026-10-27): Saxon shakos 1810 (build_p3d_reno.py SHAKO_TAGS)
HEAD += [(f"hcl_h_reno_shako_saxonia_{t}", f"hcl_shako_saxonia_{t}",
          "Shako_Saxonia_" + "_".join(x.capitalize() for x in t.split("_")), f"hcl_shako_saxonia_{t}")
         for t in ("fuzileiro", "fuzileiro_koenig", "granadeiro_gala", "ligeira", "jaeger")]
# lot 3 (2026-10-28): Westphalian shakos 1809
HEAD += [(f"hcl_h_reno_shako_vestfalia_{t}", f"hcl_shako_vestfalia_{t}",
          "Shako_Vestfalia_" + "_".join(x.capitalize() for x in t.split("_")), f"hcl_shako_vestfalia_{t}")
         for t in ("fuzileiro", "granadeiro_campanha", "granadeiro_gala", "voltigeur_gala")]


def cls_u(v):            # WUE01 -> HCL_U_Reno1811_WUE01
    return f"HCL_U_Reno1811_{v}"


def cls_s(v):
    return f"HCL_Reno1811_Soldado_{v}"


# ---------------------------------------------------------------- config.cpp
