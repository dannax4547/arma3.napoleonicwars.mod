    p3d = p3d_base + ".p3d"
    w(f"\tclass HCL_H_Varsovia1810_{suf}: H_HelmetB\n\t{{")
    w('\t\tauthor = "Historical Clothing";\n\t\tscope = 2;')
    w('\t\tdisplayName = "x";')
    w('\t\tdescriptionShort = "HCL test - no protection";')
    w('\t\tpicture = "\\A3\\characters_f\\Data\\UI\\icon_H_helmet_plain_ca.paa";')
    w(f'\t\tmodel = "{P}\\{p3d}";')
