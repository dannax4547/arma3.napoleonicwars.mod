# Writes the text sources of the in-game TEST addon hcl_varsovia (Duchy of Warsaw line infantry, regulation of
# 3 September 1810): config.cpp, model.cfg and the materials (.rvmat). Copy of gen_config_suica.py (same base classes
# and conventions); English names from nomes_en_aliados.py.
#   python gen_config_varsovia.py <project root> <variants dir> <out addon dir>
#   <variants dir>: folder of variantes_varsovia.json / variantes_varsovia_elite.json
import sys, os, json, re

ROOT, VDIR, SRC = sys.argv[1:4]
os.makedirs(os.path.join(SRC, "data"), exist_ok=True)
VAR = json.load(open(os.path.join(VDIR, "variantes_varsovia.json"), encoding="utf-8"))
ELI = json.load(open(os.path.join(VDIR, "variantes_varsovia_elite.json"), encoding="utf-8"))
P = r"\hcl\hcl_varsovia"
VIDS, EIDS = sorted(VAR), sorted(ELI)
U_P3D, E_P3D = "hcl_u_varsovia1810", "hcl_u_varsovia1810_elite"
# headgear entries: (p3d base, material base, class suffix, _co base); texture-only variants reuse a model
HEAD = [(f"hcl_h_varsovia_czapka_{t}", f"hcl_czapka_varsovia_{t}", c, f"hcl_czapka_varsovia_{t}")
        for t, c in (("fuzileiro", "Czapka_Fuzileiro"), ("voltigeur", "Czapka_Voltigeur"))]
HEAD += [(f"hcl_h_varsovia_bonnet_{t}", f"hcl_bonnet_varsovia_{t}", c, f"hcl_bonnet_varsovia_{t}")
         for t, c in (("granadeiro_gala", "Bonnet_Granadeiro_Gala"), ("granadeiro_campanha", "Bonnet_Granadeiro_Campanha"))]


def cls_u(v):            # S1 -> HCL_U_Varsovia1810_S1 ; Granadeiro_S1 -> HCL_U_Varsovia1810_Granadeiro_S1
    return f"HCL_U_Varsovia1810_{v}"


def cls_s(v):
    return f"HCL_Varsovia1810_Soldado_{v}"


# ---------------------------------------------------------------- config.cpp
o = []
w = o.append
w("// Historical Clothing - TEST addon hcl_varsovia (PBO prefix hcl\\hcl_varsovia). Personal use, in-game test only.")
w("// Generated by source/scripts/gen_config_varsovia.py (copy of gen_config_suica.py). Duchy of Warsaw line infantry,")
w("// 1810 regulation (docs/specs/aliados_fr_1812.md). No faction: the soldier classes are scope 1 (an Arma uniform needs a soldier")
w("// model); the items are scope 2 (Arsenal). Does not require hcl_fr.")
w("")
w("class CfgPatches\n{\n\tclass HCL_Varsovia_Teste\n\t{")
w('\t\tauthor = "Historical Clothing";')
w("\t\tunits[] = {};")
weapons = [cls_u(v) for v in VIDS + EIDS] + [f"HCL_H_Varsovia1810_{h[2]}" for h in HEAD]
w("\t\tweapons[] = {" + ", ".join(f'"{x}"' for x in weapons) + "};")
w("\t\trequiredVersion = 0.1;")
w('\t\trequiredAddons[] = {"A3_Characters_F"};')
w("\t};\n};\n")

w("class CfgVehicles\n{")
w("\tclass B_Soldier_base_F;\n")
for base, model, first, label, ids, vardb in (("HCL_Varsovia1810_Soldado_Base", U_P3D, VIDS[0], "x", VIDS, VAR),
                                              ("HCL_Varsovia1810_Soldado_Elite_Base", E_P3D, EIDS[0], "x", EIDS, ELI)):
    parent = "B_Soldier_base_F" if base.endswith("Soldado_Base") else "HCL_Varsovia1810_Soldado_Base"
    w(f"\tclass {base}: {parent}\n\t{{")
    if parent == "B_Soldier_base_F":
        w('\t\tauthor = "Historical Clothing";')
        w("\t\tscope = 1;")
    w('\t\tdisplayName = "x";')
    w(f'\t\tmodel = "{P}\\{model}.p3d";')
    if parent == "B_Soldier_base_F":
        w("\t\tmodelSides[] = {0, 1, 2, 3};")
    w(f'\t\tuniformClass = "{cls_u(first)}";')
    if parent == "B_Soldier_base_F":
        w('\t\thiddenSelections[] = {"Camo"};')
    w(f'\t\thiddenSelectionsTextures[] = {{"{P}\\data\\{vardb[first]["prefixo"]}_co.paa"}};')
    if parent == "B_Soldier_base_F":
        w('\t\tweapons[] = {"Throw", "Put"};\n\t\trespawnWeapons[] = {"Throw", "Put"};')
        w("\t\tmagazines[] = {};\n\t\trespawnMagazines[] = {};\n\t\tItems[] = {};\n\t\tRespawnItems[] = {};")
        w('\t\tlinkedItems[] = {"ItemMap", "ItemCompass", "ItemWatch"};')
        w('\t\trespawnLinkedItems[] = {"ItemMap", "ItemCompass", "ItemWatch"};')
    w("\t};")
    for v in ids:
        w(f"\tclass {cls_s(v)}: {base}\n\t{{")
        w('\t\tdisplayName = "x";')
        w(f'\t\tuniformClass = "{cls_u(v)}";')
        w(f'\t\thiddenSelectionsTextures[] = {{"{P}\\data\\{vardb[v]["prefixo"]}_co.paa"}};')
        w("\t};")
w("};\n")

w("class CfgWeapons\n{")
w("\tclass ItemCore;\n\tclass UniformItem;\n\tclass Uniform_Base;")
w("\tclass H_HelmetB: ItemCore\n\t{\n\t\tclass ItemInfo;\n\t};\n")
for v in VIDS + EIDS:
    w(f"\tclass {cls_u(v)}: Uniform_Base\n\t{{")
    w('\t\tauthor = "Historical Clothing";\n\t\tscope = 2;')
    w('\t\tdisplayName = "x";')
    w('\t\tpicture = "\\A3\\characters_f\\data\\ui\\icon_U_BasicBody_ca.paa";')
